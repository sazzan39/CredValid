// Copies the compiled ABI from Foundry's output so the frontend never hand-writes it.
//   (cd ../contracts && forge build) && npm run abi
import { readFileSync, writeFileSync } from "node:fs";
const artifact = JSON.parse(readFileSync(new URL("../../contracts/out/CredValidRegistry.sol/CredValidRegistry.json", import.meta.url)));
const out = `// Generated by scripts/sync-abi.mjs from contracts/out — do not edit by hand.\nexport const credValidRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
writeFileSync(new URL("../src/registry/abi.ts", import.meta.url), out);
console.log(`ABI synced: ${artifact.abi.length} entries`);
